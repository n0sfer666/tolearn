use tolearn_core::verdict::VerdictError;

use super::paper::Paper;

pub fn prompt(paper: &Paper<'_>) -> String {
    let stage = paper.stage;
    let questions: Vec<String> = stage
        .questions
        .iter()
        .map(|question| {
            let answer = paper
                .answers
                .get(&question.id)
                .map(|text| text.trim())
                .filter(|text| !text.is_empty())
                .unwrap_or("нет ответа");
            format!(
                "Вопрос {}: {}\nЭталон: {}\nОтвет ученика:\n{answer}",
                question.id, question.text, question.answer
            )
        })
        .collect();
    let format = format!(
        r#"{{"stage": "{}", "per_question": [{{"id": "q1", "result": "ok"}}, {{"id": "q2", "result": "ok", "added": "поправка или деталь своими словами"}}, {{"id": "q3", "result": "partial", "missed": ["какая суть упущена"]}}]}}"#,
        stage.id
    );
    format!(
        "Ты принимаешь письменный зачёт по этапу учебной программы «{}» (id этапа: {}).\n\n\
         Уровень ученика: {}\n\
         Язык программы: {} — на нём пиши missed и added.\n\n\
         Оценивай, передал ли ученик суть, а не повторил ли он эталон: эталон — ориентир, что считать сутью, а не список обязательных формулировок.\n\
         - ok — суть передана, пусть своими словами и без деталей эталона; ошибка в детали при верной сути оценку не снижает: поправь её в added;\n\
         - partial — суть передана только по части вопроса: вопрос спрашивает о нескольких вещах, а верная суть есть не обо всех: по остальным ответа нет или суть неверна;\n\
         - miss — суть неверна, даже если ответ близок к эталону по словам, или ответа нет.\n\n\
         Правила:\n\
         - Оценивай только написанное: не додумывай за ученика и не засчитывай то, чего в ответе нет.\n\
         - Не хвали и не смягчай оценку: вежливость — не повод поднять её.\n\
         - У partial и miss перечисли в missed только упущенную суть, по пункту на строку, — не детали эталона. У ok missed не нужен.\n\
         - У ok можешь добавить added — одну строку: деталь, которой нет в ответе и которую полезно знать, или поправку ошибки в детали. Пиши своими словами, не копией эталона: эталон ученик и так увидит. Нечего добавить или поправить — added не пиши. У partial и miss added не нужен.\n\
         - Оцени каждый вопрос ровно один раз, id бери из заголовков вопросов.\n\n\
         {}\n\n\
         Можешь сначала коротко разобрать ответы, но закончи ответ блоком JSON:\n{format}",
        stage.title,
        stage.id,
        paper.level,
        paper.locale,
        questions.join("\n\n")
    )
}

pub(super) fn repair(task: &str, answer: &str, error: &VerdictError) -> String {
    format!(
        "{task}\n\n\
         Твой прошлый ответ:\n{answer}\n\n\
         Вердикт из него не разобран: {error}\n\n\
         Пришли разбор заново и закончи его блоком JSON в том же формате, по строке на каждый вопрос."
    )
}
